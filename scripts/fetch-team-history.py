"""
Regenerate app/data/teamHistory.ts: each 2026 constructor's all-time record up to
the end of 2025, from the Jolpica-F1 API (https://api.jolpi.ca). The site adds
the 2026 season on top from the live results, the same way driver careers work.

    python3 scripts/fetch-team-history.py

Counts are for the constructor's current identity (e.g. Alpine since 2021, not
Renault), counted from race results, so a 1950s shared drive can count a win
twice. Poles are starts from P1 on the grid: Jolpica's qualifying data only
goes back to 1994, the grid back to 1950. Constructors' titles aren't queryable
per team, so they're listed by hand below.
"""

from __future__ import annotations

import json
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "data" / "teamHistory.ts"
API = "https://api.jolpi.ca/ergast/f1"

# Our team id -> Jolpica constructorId (2026 grid).
TEAMS = {
    "mclaren": "mclaren", "ferrari": "ferrari", "redbull": "red_bull", "mercedes": "mercedes",
    "astonmartin": "aston_martin", "alpine": "alpine", "williams": "williams", "racingbulls": "rb",
    "haas": "haas", "audi": "audi", "cadillac": "cadillac",
}
# Constructors' championships up to and including 2025.
TITLES = {
    "mclaren": 10, "ferrari": 16, "redbull": 6, "mercedes": 8, "astonmartin": 0, "alpine": 0,
    "williams": 9, "racingbulls": 0, "haas": 0, "audi": 0, "cadillac": 0,
}


def total(path: str) -> int:
    for attempt in range(5):
        try:
            with urllib.request.urlopen(f"{API}/{path}.json?limit=1", timeout=30) as res:
                n = int(json.load(res)["MRData"]["total"])
            time.sleep(0.35)  # stay under Jolpica's ~4 requests/second
            return n
        except urllib.error.HTTPError as e:
            if e.code != 429 or attempt == 4:
                raise
            time.sleep(3 * (attempt + 1))


def main():
    rows = {}
    for team, cid in TEAMS.items():
        def before_2026(path: str) -> int:
            # All-time minus this season = up to the end of 2025.
            return total(f"constructors/{cid}/{path}") - total(f"2026/constructors/{cid}/{path}")
        wins = before_2026("results/1")
        podiums = wins + before_2026("results/2") + before_2026("results/3")
        rows[team] = {
            "titles": TITLES[team],
            "wins": wins,
            "podiums": podiums,
            "poles": before_2026("grid/1/results"),
        }
        print(team, rows[team])

    lines = [
        "// Generated by scripts/fetch-team-history.py from the Jolpica-F1 API — don't edit by hand.",
        'import type { TeamId } from "./standings";',
        "",
        "export type TeamHistory = {",
        "  /** Constructors' championships up to the end of 2025. */",
        "  titles: number;",
        "  wins: number;",
        "  podiums: number;",
        "  /** Starts from pole position. */",
        "  poles: number;",
        "};",
        "",
        "/** Each constructor's record up to the end of 2025; 2026 is added from the live results. */",
        "export const teamHistoryBefore2026: Record<TeamId, TeamHistory> = {",
        *(f"  {team}: {{ titles: {r['titles']}, wins: {r['wins']}, podiums: {r['podiums']}, poles: {r['poles']} }},"
          for team, r in rows.items()),
        "};",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(rows)} teams to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
