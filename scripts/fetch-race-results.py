"""
Regenerate app/data/raceResults.ts: the full race (and sprint)
classification and pole sitter of every 2026 round run so far, from the Jolpica-F1 API (https://api.jolpi.ca).

The site fetches this live (app/lib/f1.ts); the generated file is only the offline
fallback, so refresh it now and then to keep that fallback recent.

    python3 scripts/fetch-race-results.py
"""

import json
import re
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "data" / "raceResults.ts"
API = "https://api.jolpi.ca/ergast/f1/2026"

# Jolpica constructorId -> our team id in app/data/standings.ts
TEAMS = {
    "red_bull": "redbull",
    "aston_martin": "astonmartin",
    "rb": "racingbulls",
    "sauber": "audi",
}


def get(url: str):
    with urllib.request.urlopen(url, timeout=30) as res:
        return json.load(res)


def our_names() -> dict[str, str]:
    """Family name -> the display name used in standings.ts (e.g. Kimi Antonelli)."""
    src = (ROOT / "app" / "data" / "standings.ts").read_text()
    names = re.findall(r'\{ name: "([^"]+)", team:', src)
    return {n.split(" ", 1)[1]: n for n in names}


def gap(row: dict, winner_laps: int) -> str:
    """Race time for the winner, gap for others on the lead lap, else laps down or the status."""
    if row["positionText"].isdigit():
        # Laps down first: for lapped cars Jolpica's "time" isn't a gap to the winner.
        down = winner_laps - int(row["laps"])
        if down > 0:
            return f"+{down} lap{'s' if down > 1 else ''}"
        if row.get("Time", {}).get("time"):
            return row["Time"]["time"]
        return row["status"]
    return {"R": "DNF", "D": "DSQ", "W": "DNS", "N": "NC", "E": "EXC", "F": "DNQ"}.get(
        row["positionText"], row["status"]
    )


def classify(results: list, names: dict[str, str]) -> list[dict]:
    winner_laps = int(results[0]["laps"])
    rows = []
    for r in results:
        d = r["Driver"]
        cid = r["Constructor"]["constructorId"]
        pts = float(r["points"])
        rows.append({
            "position": r["positionText"],
            "name": names.get(d["familyName"], f'{d["givenName"]} {d["familyName"]}'),
            "team": TEAMS.get(cid, cid),
            "gap": gap(r, winner_laps),
            "points": int(pts) if pts.is_integer() else pts,
            "fastestLap": r.get("FastestLap", {}).get("rank") == "1",
        })
    return rows


def ts_table(name: str, doc: str, rounds: dict[int, list[dict]]) -> list[str]:
    lines = [f"/** {doc} */", f"export const {name}: Record<number, ClassifiedRow[]> = {{"]
    for rnd, rows in rounds.items():
        lines.append(f"  {rnd}: [")
        for row in rows:
            lines.append(
                f'    {{ position: {json.dumps(row["position"])}, name: {json.dumps(row["name"], ensure_ascii=False)}, '
                f'team: {json.dumps(row["team"])}, gap: {json.dumps(row["gap"])}, points: {row["points"]}'
                + (", fastestLap: true" if row["fastestLap"] else "")
                + " },"
            )
        lines.append("  ],")
    lines.append("};")
    return lines


def main():
    names = our_names()
    races, sprints, poles = {}, {}, {}
    for rnd in range(1, 30):
        race = get(f"{API}/{rnd}/results.json?limit=40")["MRData"]["RaceTable"]["Races"]
        if not race:
            break
        races[rnd] = classify(race[0]["Results"], names)
        time.sleep(0.3)  # stay under Jolpica's ~4 requests/second
        sprint = get(f"{API}/{rnd}/sprint.json?limit=40")["MRData"]["RaceTable"]["Races"]
        if sprint:
            sprints[rnd] = classify(sprint[0]["SprintResults"], names)
        time.sleep(0.3)
        quali = get(f"{API}/{rnd}/qualifying/1.json")["MRData"]["RaceTable"]["Races"]
        if quali:
            d = quali[0]["QualifyingResults"][0]["Driver"]
            poles[rnd] = names.get(d["familyName"], f'{d["givenName"]} {d["familyName"]}')
        time.sleep(0.3)

    lines = [
        "// Generated by scripts/fetch-race-results.py from the Jolpica-F1 API — don't edit by hand.",
        "// Offline snapshot: the site fetches live results (app/lib/f1.ts) and only falls back to this",
        "// when the API can't be reached.",
        'import type { teams } from "./standings";',
        "",
        "export type ClassifiedRow = {",
        '  /** "1", "2", … or "R" (retired), "D" (disqualified), "W" (withdrawn), "N" (not classified). */',
        "  position: string;",
        "  name: string;",
        "  team: keyof typeof teams;",
        '  /** Race time for the winner, otherwise the gap, laps down, or "DNF" etc. */',
        "  gap: string;",
        "  points: number;",
        "  /** Set the race's fastest lap. */",
        "  fastestLap?: boolean;",
        "};",
        "",
        *ts_table("raceResults", "Full race classification for each finished round.", races),
        "",
        *ts_table("sprintResults", "Sprint classification, for sprint weekends only.", sprints),
        "",
        "/** Pole sitter for each round. */",
        "export const poleSitters: Record<number, string> = {",
        *(f"  {rnd}: {json.dumps(name, ensure_ascii=False)}," for rnd, name in poles.items()),
        "};",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(races)} races and {len(sprints)} sprints to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
